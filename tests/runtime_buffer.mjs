import buffer, { Buffer } from 'node:buffer';
import * as bare from 'buffer';
import { assert, equal, finish } from './assert.js';

assert(globalThis.Buffer === Buffer && bare.Buffer === buffer.Buffer, 'Buffer import identity');
const backing = new ArrayBuffer(8), view = Buffer.from(backing, 2, 4), copy = Buffer.from(view);
view.fill(7);
equal(copy[0], 0);
equal(new Uint8Array(backing)[2], 7);
view.slice(1, 2)[0] = 9;
equal(view[1], 9);
assert(Buffer.isBuffer(view.subarray(1)) && view instanceof Uint8Array);
const text = '中文😀';
equal(Buffer.from(text).toString('base64url'), '5Lit5paH8J-YgA');
equal(Buffer.from('5Lit5paH8J-YgA', 'base64url').toString(), text);
equal(Buffer.from('aa!bb', 'hex').toString('hex'), 'aa');
equal(Buffer.from('\ud800').toString('hex'), 'efbfbd');
equal(Buffer.concat([Buffer.from('a'), new Uint8Array([98])]).toString(), 'ab');
assert(Buffer.from('ab').equals(Buffer.from([97, 98])));
assert(Buffer.compare(Buffer.from('a'), Buffer.from('b')) < 0);
const overlap = Buffer.from('abcdef');
equal(overlap.copy(overlap, 2, 0, 4), 4);
equal(overlap.toString(), 'ababcd');
const numeric = Buffer.alloc(16);
equal(numeric.writeUIntLE(2 ** 40 + 1, 2, 6), 8);
equal(numeric.readUIntLE(2, 6), 2 ** 40 + 1);
numeric.writeBigInt64BE(-1n, 8);
equal(numeric.readBigInt64BE(8), -1n);
numeric.writeDoubleLE(Math.PI, 0);
equal(numeric.readDoubleLE(0), Math.PI);
equal(Buffer.from('ababa').lastIndexOf('ba'), 3);
equal(Buffer.from([1, 2, 3, 4]).swap16().toString('hex'), '02010403');
const decoder = new TextDecoder();
equal(decoder.decode(new Uint8Array([240, 159]), { stream: true }), '');
equal(decoder.decode(new Uint8Array([152, 128])), '😀');
const destination = new Uint8Array(3);
equal(new TextEncoder().encodeInto('😀', destination).written, 0);
assert(Buffer.allocUnsafe(8).every(byte => byte === 0), 'Unsafe allocation is intentionally zeroed');
equal(buffer.constants.MAX_LENGTH, buffer.kMaxLength);
equal(buffer.constants.MAX_STRING_LENGTH, buffer.kStringMaxLength);
equal(buffer.kMaxLength, 0x7fffffff);
let quotaError;
try { Buffer.alloc(0x80000000); } catch (error) { quotaError = error.code; }
equal(quotaError, 'ERR_OUT_OF_RANGE');
const resizable = new ArrayBuffer(8, { maxByteLength: 16 });
let resizeError;
try { Buffer.from(resizable); } catch (error) { resizeError = error.code; }
equal(resizeError, 'ERR_NOT_SUPPORTED', 'Resizable backing stores fail explicitly');
finish('runtime-buffer');
