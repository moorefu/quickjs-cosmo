import * as std from 'std';
import * as qjsOS from 'os';
import process from 'node:process';
import path from 'node:path';
import posix from 'node:path/posix';
import win32 from 'node:path/win32';
import os from 'node:os';
import { EventEmitter } from 'node:events';
import { promisify } from 'node:util';
import assert from 'node:assert/strict';
import { main as childMain, url as childURL } from './fixtures/foundation-import.mjs';
import { equal, finish } from './assert.js';

assert.equal(globalThis.process, process);
assert.equal(process.platform, qjsOS.platform);
assert.equal(os.platform(), process.platform);
assert.equal(os.arch(), process.arch);
assert.equal(path.posix, posix); assert.equal(path.win32, win32);
assert.equal(process.versions.quickjs, '2026-06-04');
assert.equal(process.versions.node, undefined); assert.equal(process.versions.v8, undefined);
assert(process instanceof EventEmitter);
assert.equal(import.meta.main, true);
assert.equal(childMain, false);
const compiled = process.argv[1] === process.execPath && process.execArgv.length === 0;
assert(childURL.startsWith(compiled ? 'qjs:embedded/' : 'file:'));
if (compiled) assert(!childURL.includes('/Workspace/') && !childURL.includes('/home/runner/') && !childURL.includes('/mnt/'));
assert(process.pid > 0 && process.ppid >= 0);
assert(path.isAbsolute(process.execPath));
assert.equal(typeof process.hrtime.bigint(), 'bigint');
const emitter = new EventEmitter(), calls = [];
emitter.once('x', value => calls.push(value)); emitter.emit('x', 1); emitter.emit('x', 2);
assert.equal(calls.join(','), '1');
const wrapped = promisify(function (a, done) { done(null, this.base + a); });
assert.equal(await wrapped.call({ base: 3 }, 4), 7);
assert.equal(process.env.QJS_FOUNDATION_MIRROR, undefined);
process.env.QJS_FOUNDATION_MIRROR = '中文😀';
assert.equal(std.getenv('QJS_FOUNDATION_MIRROR'), '中文😀');
delete process.env.QJS_FOUNDATION_MIRROR;
assert.equal(std.getenv('QJS_FOUNDATION_MIRROR'), undefined);
const original = process.cwd();
process.chdir(os.tmpdir());
const [currentDirectory, currentError] = qjsOS.realpath(process.cwd());
const [temporaryDirectory, temporaryError] = qjsOS.realpath(os.tmpdir());
assert.equal(currentError, 0); assert.equal(temporaryError, 0);
assert.equal(currentDirectory, temporaryDirectory);
if (process.platform === 'win32') assert(/^(?:[A-Za-z]:\\|\\\\)/.test(process.cwd()));
process.chdir(original);
const previous = process.env.QJS_FOUNDATION_WORKER_SNAPSHOT;
process.env.QJS_FOUNDATION_WORKER_SNAPSHOT = 'created';
process.argv.push('snapshot-argument');
const worker = new qjsOS.Worker('./fixtures/foundation-worker.mjs');
process.argv.pop();
process.env.QJS_FOUNDATION_WORKER_SNAPSHOT = 'parent-after';
const watchdog = qjsOS.setTimeout(() => { std.err.puts('Foundation Worker timeout\n'); std.exit(1); }, 10000);
try {
    const reply = await new Promise(resolve => {
        worker.onmessage = ({ data }) => resolve(data);
        worker.postMessage('inspect');
    });
    worker.onmessage = null;
    assert.equal(reply.value, 'created');
    assert.equal(reply.local, 'worker-only');
    assert.equal(reply.argvTail, 'snapshot-argument');
    assert.equal(reply.pid, process.pid);
    assert.equal(reply.main, true); assert.equal(reply.importedMain, false);
    assert.equal(reply.globals, true);
    assert.equal(reply.codes.join(','), Array(3).fill('ERR_WORKER_UNSUPPORTED_OPERATION').join(','));
    assert.equal(process.env.QJS_FOUNDATION_WORKER_SNAPSHOT, 'parent-after');
    assert(reply.url.startsWith('file:'));
} finally {
    worker.onmessage = null; qjsOS.clearTimeout(watchdog);
    if (previous === undefined) delete process.env.QJS_FOUNDATION_WORKER_SNAPSHOT;
    else process.env.QJS_FOUNDATION_WORKER_SNAPSHOT = previous;
}
std.gc();
equal(Buffer.from('abc').toString(), 'abc', 'Bootstrap survives a full GC');
finish('runtime-foundation');
